alter table public.quotes
  add column if not exists user_id uuid references auth.users (id) on delete cascade,
  add column if not exists quote_id text,
  add column if not exists file_path text,
  add column if not exists config jsonb,
  add column if not exists estimate jsonb,
  add column if not exists notes text,
  add column if not exists created_at timestamptz not null default now();

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  serial_number bigint generated by default as identity unique,
  order_number text unique,
  user_id uuid not null references auth.users (id) on delete cascade,
  file_url text not null,
  material text not null,
  color text not null,
  infill integer not null,
  layer_height numeric not null,
  supports boolean not null default false,
  full_name text not null default '',
  phone text not null default '',
  address_line1 text not null default '',
  address_line2 text,
  city text not null default '',
  state text not null default '',
  pincode text not null default '',
  landmark text,
  delivery_charge numeric(10,2) not null default 0,
  total_price numeric(10,2) not null default 0,
  price numeric(10,2) not null,
  estimated_time numeric(10,2) not null,
  status text not null default 'pending',
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint orders_status_check check (
    status in ('pending', 'reviewed', 'approved', 'printing', 'completed', 'rejected')
  )
);

create table if not exists public.delivery_addresses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  full_name text not null,
  phone text not null,
  address_line1 text not null,
  address_line2 text,
  city text not null,
  state text not null,
  pincode text not null,
  landmark text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.materials (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  price_per_gram numeric(10,2) not null default 0,
  density numeric(10,2) not null default 0,
  colors jsonb not null default '[]'::jsonb,
  stock text not null default 'Healthy',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint materials_stock_check check (stock in ('Healthy', 'Low', 'Paused'))
);

